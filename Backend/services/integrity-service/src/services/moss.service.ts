  /**
   * Store MOSS results in database
   */
  private async storeMossResults(
    assessmentId: string,
    problemId: string,
    reportUrl: string,
    matches: any[],
    submissions: MossSubmission[]
  ): Promise<void> {
    const client = await pool.connect();

    try {
      await client.query('BEGIN');

      // Update submissions with MOSS report URL
      for (const submission of submissions) {
        await client.query(
          `UPDATE code_submissions
           SET moss_report_url = $1,
               updated_at = NOW()
           WHERE user_id = $2 AND assessment_id = $3 AND problem_id = $4`,
          [reportUrl, submission.userId, assessmentId, problemId]
        );
      }

      // Store matches in plagiarism_matches table
      for (const match of matches) {
        // Find submission IDs
        const sub1 = await client.query(
          `SELECT id FROM code_submissions
           WHERE assessment_id = $1 AND problem_id = $2 AND file_name = $3
           ORDER BY submitted_at DESC LIMIT 1`,
          [assessmentId, problemId, match.file1]
        );

        const sub2 = await client.query(
          `SELECT id FROM code_submissions
           WHERE assessment_id = $1 AND problem_id = $2 AND file_name = $3
           ORDER BY submitted_at DESC LIMIT 1`,
          [assessmentId, problemId, match.file2]
        );

        if (sub1.rows.length > 0 && sub2.rows.length > 0) {
          await client.query(
            `INSERT INTO plagiarism_matches (
              submission1_id, submission2_id, similarity_score,
              matching_lines, algorithm, match_details
            )
            VALUES ($1, $2, $3, $4, 'moss', $5)
            ON CONFLICT DO NOTHING`,
            [
              sub1.rows[0].id,
              sub2.rows[0].id,
              match.percentage / 100,
              match.linesMatched,
              JSON.stringify({ reportUrl, mossMatch: match }),
            ]
          );

          // Flag submissions if similarity is high
          if (match.percentage >= 80) {
            await client.query(
              `UPDATE code_submissions
               SET is_flagged = true, plagiarism_status = 'plagiarized'
               WHERE id IN ($1, $2)`,
              [sub1.rows[0].id, sub2.rows[0].id]
            );
          }
        }
      }

      await client.query('COMMIT');
      console.log('[MOSS] Results stored successfully');
    } catch (error) {
      await client.query('ROLLBACK');
      console.error('[MOSS] Failed to store results:', error);
      throw error;
    } finally {
      client.release();
    }
  }

  /**
   * Trigger MOSS check for an assessment
   */
  async checkAssessmentPlagiarism(assessmentId: string, problemId: string): Promise<void> {
    try {
      // Get all submissions for this problem
      const result = await pool.query(
        `SELECT
          cs.id,
          cs.user_id,
          cs.code,
          cs.file_name,
          cs.language
         FROM code_submissions cs
         WHERE cs.assessment_id = $1 AND cs.problem_id = $2
         ORDER BY cs.submitted_at DESC`,
        [assessmentId, problemId]
      );

      if (result.rows.length < 2) {
        console.log('[MOSS] Not enough submissions for plagiarism check');
        return;
      }

      const submissions: MossSubmission[] = result.rows.map((row) => ({
        userId: row.user_id,
        code: row.code,
        fileName: row.file_name || `user_${row.user_id}.${this.getFileExtension(row.language)}`,
      }));

      const language = result.rows[0].language;

      // Submit to MOSS
      const mossResult = await this.submitToMoss(assessmentId, problemId, language, submissions);

      if (mossResult) {
        console.log(`[MOSS] Check complete. Report: ${mossResult.reportUrl}`);
        console.log(`[MOSS] Found ${mossResult.matches.length} matches`);
      }
    } catch (error) {
      console.error('[MOSS] Assessment check failed:', error);
      throw error;
    }
  }

  /**
   * Get file extension for language
   */
  private getFileExtension(language: string): string {
    const extensions: { [key: string]: string } = {
      javascript: 'js',
      typescript: 'ts',
      python: 'py',
      java: 'java',
      cpp: 'cpp',
      c: 'c',
      csharp: 'cs',
      ruby: 'rb',
      go: 'go',
      rust: 'rs',
      php: 'php',
    };

    return extensions[language.toLowerCase()] || 'txt';
  }

  /**
   * Get MOSS report URL for submission
   */
  async getMossReportUrl(submissionId: string): Promise<string | null> {
    const result = await pool.query(
      'SELECT moss_report_url FROM code_submissions WHERE id = $1',
      [submissionId]
    );

    if (result.rows.length === 0) {
      return null;
    }

    return result.rows[0].moss_report_url;
  }
